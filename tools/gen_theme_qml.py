#!/usr/bin/env python3
"""Generate a QML shell's Theme singleton from personality/theme.toml.

Theme tokens are identity (CLAUDE.md invariant 9), so they live in
`personality/` beside the voice and the system prompt — not scattered
through QML as hex codes nobody can diff. This generator turns that one
file into, for each shell in `SHELLS`:

  shell/<shell>/Theme.qml   a `pragma Singleton` QtObject of readonly tokens
  shell/<shell>/Ease.qml    the one gated Behavior every moving value uses
  shell/<shell>/Motion.qml  the singleton that says whether it may move at all
  shell/<shell>/core/MotionPolicy.qml  the decision behind it, in pure QtQuick
  shell/<shell>/qmldir      the registration that makes `import "."` work
  shell/<shell>/core/qmldir the same for the Quickshell-free half

There are three shells — `jv-hud`, the corner overlay, `jv-bar`, the top
bar, and `jv-notify`, the notification corner — and they get the SAME
Theme.qml, byte for byte. Not a shared import: each shell is copied into the
store on its own and `import "."` resolves inside one directory, so the file
has to exist in all of them. Generating them from one renderer is what keeps
"the HUD's corner, the bar's strip and a toast are one identity" a fact
rather than a hope.

The motion trio is here for the same reason and it matters more (PLAN D18):
`Ease` + `Motion` + `core/MotionPolicy` is the one place §06's stillness rule
is decidable — declared preference, session override, battery, fullscreen —
and a hand-copied second version of a DECISION is a second thing to drift.
Before this, only jv-hud had it: the bar could not move at all and the
notifier gated its one fade on the raw preference, honouring the versioned
token and nothing else. Now every shell gets the same three files, and the
byte-for-byte check below is what says all three still obey one switch.

Every output is checked in (so qmllint and the editor see them) and every
one is verified with `--check`, which runs in each shell's own build: a
Theme.qml that has drifted from theme.toml cannot reach a `nixos-rebuild
build`.

Usage:
  python tools/gen_theme_qml.py                    # write every shell's files
  python tools/gen_theme_qml.py --check            # exit 1 if any differ
  python tools/gen_theme_qml.py --shell jv-bar ... # one shell only

It also writes the files that are not any shell's: one
`<harness>/stub/Motion.qml` per entry in `STANDINS`, the stand-in a render
harness stages over its shell's Motion because the shots run under an engine
that cannot resolve Quickshell. Each is rendered from the same body as the real
one with three lines swapped (PLAN D29), so what a sheet photographs animates
for the reason the running shell would. There are three, one per shell: the
HUD's contact sheet (`ops/ralph/hudshots.sh`), the notification corner's
(`notifyshots.sh`, PLAN D20) and the top bar's (`barshots.sh`, PLAN D13).
"""

