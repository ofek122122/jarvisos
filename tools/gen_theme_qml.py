@dataclasses.dataclass(frozen=True)
class Shell:
    """One QML shell that consumes the tokens, and what its qmldirs list.

    `name` is the directory under `shell/` and the package name. `owner` is
    how the core qmldir refers to the shell in prose, and `registry` is the
    prefix of the three tables above — both exist so the generated comment
    names the table a reader has to edit, which is the whole point of writing
    a comment into a generated file.

    The three tuples are the FULL registries — the shell's own hand-written
    types with everything this script generates already in front of them (see
    `_shell`), because "what the qmldir lists" and "what is in the directory"
    is one question and a reader of either should get one answer.
    """

    name: str
    owner: str
    registry: str
    singletons: tuple[tuple[str, str], ...]
    components: tuple[tuple[str, str], ...]
    core: tuple[tuple[str, str], ...]


def _shell(
    name: str,
    owner: str,
    registry: str,
    singletons: tuple[tuple[str, str], ...],
    components: tuple[tuple[str, str], ...],
    core: tuple[tuple[str, str], ...],
) -> Shell:
    """One shell: its hand-written tables, behind the generated ones.

    The generated types come FIRST in every registry so the qmldir opens with
    the four files this script owns — a reader who wants to know why a line is
    there gets "because the generator writes it into every shell" before the
    shell's own vocabulary starts.
    """
    return Shell(
        name,
        owner,
        registry,
        GENERATED_SINGLETONS + singletons,
        GENERATED_COMPONENTS + components,
        GENERATED_CORE + core,
    )


